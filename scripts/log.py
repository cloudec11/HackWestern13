#!/usr/bin/env python3
"""Change-log helper for the multi-agent workflow.

Each agent appends to its OWN file (logs/agent-N.md), so agents never write to
the same file and never cause merge conflicts. `merge` rebuilds LOG.md, a
combined newest-first view, from all per-agent files.

Usage:
  python scripts/log.py add --agent 1 --task P1-1 --summary "pod-capture writes ring buffer" \
      --files pod/capture/main.cpp pod/ipc/ring.h [--status DONE] [--notes "..."]
  python scripts/log.py merge           # rebuild LOG.md
  python scripts/log.py show [--agent N] [--limit 20]
"""
import argparse
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOGS = ROOT / "logs"
MERGED = ROOT / "LOG.md"
ENTRY_RE = re.compile(r"^## (\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}) \| agent-(\d+) \|", re.M)


def agent_file(n: int) -> Path:
    return LOGS / f"agent-{n}.md"


def add(a):
    LOGS.mkdir(exist_ok=True)
    path = agent_file(a.agent)
    if not path.exists():
        path.write_text(f"# Agent {a.agent} log\n\nAppend-only. Written by agent-{a.agent} only.\n\n", encoding="utf-8")
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [f"## {ts} | agent-{a.agent} | {a.task or '-'} | {a.status}", f"**What:** {a.summary}"]
    if a.files:
        lines.append("**Files:** " + ", ".join(f"`{f}`" for f in a.files))
    if a.notes:
        lines.append(f"**Notes:** {a.notes}")
    with path.open("a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n\n")
    print(f"logged to {path.relative_to(ROOT)}")
    # LOG.md is NOT rebuilt here on purpose: every agent rebuilding it on every
    # commit would cause merge conflicts. Run `merge` on demand instead.


def read_entries(only_agent=None):
    entries = []
    for f in sorted(LOGS.glob("agent-*.md")):
        text = f.read_text(encoding="utf-8")
        parts = ENTRY_RE.split(text)
        # parts: [preamble, ts, agent, body, ts, agent, body, ...]
        for i in range(1, len(parts), 3):
            ts, ag, body = parts[i], int(parts[i + 1]), parts[i + 2]
            if only_agent is None or ag == only_agent:
                entries.append((ts, ag, body.rstrip("\n")))
    entries.sort(key=lambda e: e[0], reverse=True)
    return entries


def merge(_):
    entries = read_entries()
    out = [
        "# LOG — all agent changes (newest first)",
        "",
        "GENERATED by `python scripts/log.py merge`. Do not edit by hand.",
        "Source of truth: `logs/agent-N.md`.",
        "",
    ]
    if not entries:
        out.append("_No entries yet._")
    for ts, ag, body in entries:
        out.append(f"## {ts} | agent-{ag} |{body}")
        out.append("")
    MERGED.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"rebuilt {MERGED.name} ({len(entries)} entries)")


def show(a):
    for ts, ag, body in read_entries(a.agent)[: a.limit]:
        print(f"{ts} | agent-{ag} |{body}\n")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("add")
    s.add_argument("--agent", type=int, required=True)
    s.add_argument("--task", default="")
    s.add_argument("--summary", required=True)
    s.add_argument("--files", nargs="*", default=[])
    s.add_argument("--status", default="DONE", choices=["DOING", "DONE", "BLOCKED", "REVIEW", "CONTRACT"])
    s.add_argument("--notes", default="")
    s.set_defaults(fn=add)
    sub.add_parser("merge").set_defaults(fn=merge)
    s = sub.add_parser("show")
    s.add_argument("--agent", type=int)
    s.add_argument("--limit", type=int, default=20)
    s.set_defaults(fn=show)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
